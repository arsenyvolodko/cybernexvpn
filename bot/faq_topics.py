"""Разделы FAQ.

Раскрывающиеся пункты, а не простыня: человек с вопросом «почему не работает»
не должен читать про тарифы. Каждый раздел — отдельный экран, из него «Назад»
возвращает в список.

Тексты объясняют, **что делать**, а не как устроены протоколы. Слов «REALITY»,
«gRPC» и «Hysteria» здесь нет намеренно: они ничего не говорят человеку,
который просто хочет, чтобы заработало.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Topic:
    key: str
    button: str
    body: str


PROFILES = Topic(
    key="profiles",
    button="Почему профилей много и какой выбрать 🧭",
    body=(
        "<b>Почему в списке много профилей</b>\n\n"
        "Это не разные подписки и не разные тарифы — это разные <b>дороги</b> "
        "до одного и того же интернета. Блокировки в России устроены так, что у "
        "одного человека проходит одна дорога, у соседа с другим оператором — "
        "совсем другая. Заранее угадать нельзя, поэтому мы даём сразу несколько.\n\n"
        "<b>Как читать список</b>\n\n"
        "Обход глушилок 1 и 2 - может помочь в регионах, когда глушат все и не работает ничего, кроме белых списков\n\n"
        "Обход глушилок через рф - работает менее стабильно чем 1 и 2, но позволяют пользоваться российскими сервисами без отключения VPN\n\n"
        "Быстрые: Франция и Нидерланды - прямые туннели в европу. Лучше работают на wifi. Если оператор в вашем регионе не блочит этот протокол - то работают быстро.\n\n"
        "Стабильные: Франция и Нидерланды - также прямые туннели в европу по альтернаитивным протоколам, если \"быстрые\" блочат.\n\n"
        "Альтернативные: 1 и 2 - лучше работают в Москве и на wifi, позволяют пользоваться российскими сервисами без отключения VPN\n\n"
        "<b>Что делать на практике</b>\n\n"
        "Нажмите на кнопочку измерения скорости (похожа на спидометр или кардио-линию в зависимости от приложения) и выберите лучший по скорости.\n"
        "Скорость может меняться в разное время и в различных условиях.\n"
        "Нормально, что на домашнем wi-fi работает один профиль, а на мобильном "
        "интернете другой: это разные сети и режут их по-разному. Многие держат "
        "в голове два — «домашний» и «мобильный»."
    ),
)

