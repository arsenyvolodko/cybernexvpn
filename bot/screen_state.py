"""Какой экран сейчас показан в каждом чате.

Отдельный модуль без зависимостей — намеренно: им пользуются и обработчики,
и фоновые задачи, а если положить это внутрь `bot.handlers`, импорты
замкнутся в кольцо.

Фоновая задача правит сообщение спустя минуты. За это время человек мог уйти
в другой раздел — тогда правку надо отменить, иначе затрём то, что он видит
сейчас. Метка живёт в памяти процесса: после перезапуска бота все ожидания и
так обрываются.
"""

_current: dict[int, str | None] = {}


def mark_screen(chat_id: int, screen: str | None) -> None:
    _current[chat_id] = screen


def is_current_screen(chat_id: int, screen: str) -> bool:
    return _current.get(chat_id) == screen
