def plural_days(days: int) -> str:
    """«1 день», «2 дня», «5 дней» — Telegram не прощает кривых окончаний."""
    if days % 100 in (11, 12, 13, 14):
        return f"{days} дней"
    last = days % 10
    if last == 1:
        return f"{days} день"
    if last in (2, 3, 4):
        return f"{days} дня"
    return f"{days} дней"


def plural_hours(hours: int) -> str:
    if hours % 100 in (11, 12, 13, 14):
        return f"{hours} часов"
    last = hours % 10
    if last == 1:
        return f"{hours} час"
    if last in (2, 3, 4):
        return f"{hours} часа"
    return f"{hours} часов"


def plural_devices(count: int) -> str:
    if count % 100 in (11, 12, 13, 14):
        return f"{count} устройств"
    last = count % 10
    if last == 1:
        return f"{count} устройство"
    if last in (2, 3, 4):
        return f"{count} устройства"
    return f"{count} устройств"
