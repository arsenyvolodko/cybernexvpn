"""Заготовки двух объявлений о перезапуске.

Создаёт черновики в админке, чтобы не набирать текст с разметкой руками в
поле формы. Дальше их правят и отправляют кнопками — сначала «только мне»,
потом получателям.

Двум группам нужно рассказывать разное. Тем, кто ушёл, — что мы вернулись и
дарим дни: они про нас забыли, и напоминание должно объяснять, зачем
возвращаться. Тем, кто остался, — что подписка перенесена и ничего не
потерялось: у них главный страх, что сгорели деньги.
"""

from django.core.management.base import BaseCommand

from nexvpn.enums import BroadcastAudienceEnum
from nexvpn.models import Broadcast

GIFTED = """<b>Мы вернулись — и стали работать там, где раньше не получалось</b>

Всё это время мы переделывали сервис. Теперь это не старый VPN, а несколько
разных способов обхода: когда не работает ни один привычный, срабатывает
обфускация — мы проверили её на Tele2, Билайне, МТС, МегаФоне и Yota.

Российские сайты — банки, госуслуги, маркетплейсы — теперь идут напрямую, мимо
туннеля. Быстро и без «входа из другой страны».

<b>Мы начислили тебе 30 дней бесплатно</b>, на трёх устройствах. Просто чтобы ты
попробовал, что получилось. Карту вводить не нужно."""

CONVERTED = """<b>Мы перезапустили сервис — твоя подписка уже перенесена</b>

Ничего не потерялось: и остаток оплаченного периода, и деньги на балансе
пересчитаны в дни на новом тарифе. Сколько именно получилось — видно в разделе
«Моя подписка».

Что изменилось: вместо одного способа подключения теперь несколько, и среди них
есть такие, что работают даже когда глушат всё остальное. Российские сайты идут
напрямую, мимо туннеля, — банки и госуслуги открываются быстро и не считают тебя
иностранцем.

Подключаться заново придётся один раз: старые настройки не подойдут, нужно
установить приложение и добавить подписку. Это пара минут."""


class Command(BaseCommand):
    help = "Создать черновики объявлений о перезапуске для двух групп"

    def handle(self, *args, **options):
        drafts = [
            ("Перезапуск: ушедшим (подарок 30 дней)", GIFTED, BroadcastAudienceEnum.LEGACY_GIFTED),
            ("Перезапуск: действующим (подписка перенесена)", CONVERTED, BroadcastAudienceEnum.LEGACY_CONVERTED),
        ]
        for title, text, audience in drafts:
            broadcast, created = Broadcast.objects.get_or_create(
                title=title,
                defaults={"text": text.strip(), "audience": audience, "with_connect_button": True},
            )
            state = "создан" if created else "уже был"
            self.stdout.write(f"{state}: {title}")
        self.stdout.write(
            self.style.SUCCESS(
                "Черновики в админке, раздел «Рассылки». Сначала «Отправить только мне»."
            )
        )
